// Real LiteAPI sandbox requests, one simulated order. No mocks and no production key.
import { chromium } from "playwright";
import fs from "node:fs";
import assert from "node:assert/strict";
const base = process.argv[2] || "http://127.0.0.1:3010";
const executablePath = ["C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", "C:/Program Files/Google/Chrome/Application/chrome.exe"].find((path) => fs.existsSync(path));
const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
const context = await browser.newContext({ viewport: { width: 1365, height: 950 } });
try {
  const page = await context.newPage();
  page.setDefaultTimeout(65000);
  const errors = []; let popups = 0;
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("popup", () => popups++);
  await page.goto(`${base}/booking/hotels/`); await page.waitForLoadState("networkidle");
  await page.getByRole("heading", { name: "站内订酒店", exact: true }).waitFor();
  await page.getByLabel("每晚房价上限", { exact: false }).fill("1000");
  await page.getByRole("button", { name: "查询沙盒房价" }).click();
  const choose = page.getByRole("button", { name: "选择房型并验价", exact: true });
  await choose.first().waitFor();
  assert.ok(await choose.count() > 0, "real supplier sandbox must return standalone offers");
  fs.mkdirSync(".automation", { recursive: true });
  await page.screenshot({ path: ".automation/hotel-trial-search.png", fullPage: false });
  await choose.first().click();
  const checkout = page.getByRole("region", { name: "确认报价与模拟付款" });
  await checkout.waitFor();
  const submit = page.getByRole("button", { name: "模拟付款并确认订单", exact: true });
  assert.equal(await submit.isEnabled(), false, "explicit confirmation is required");
  await page.getByRole("checkbox", { name: /我已核对/ }).check();
  assert.equal(await submit.isEnabled(), true);
  await submit.click();
  const receipt = page.getByRole("region", { name: "供应商订单结果" });
  await receipt.waitFor();
  const id = await page.getByTestId("hotel-booking-id").innerText();
  assert.ok(id.length > 0);
  assert.equal(page.url(), `${base}/booking/hotels/`);
  assert.equal(popups, 0);
  const current = await (await context.request.get(`${base}/api/hotel-trial/`)).json();
  assert.equal(current.booking.bookingId, id); assert.equal(current.booking.sandbox, true);
  assert.ok(["CONFIRMED", "PENDING", "PENDING_CONFIRMATION"].includes(current.booking.status));
  assert.equal(current.offers[0].supplierOfferId, undefined);
  const duplicate = await context.request.post(`${base}/api/hotel-trial/`, { data: { action: "book", prebookId: current.prebook.id } });
  assert.equal(duplicate.status(), 200); assert.equal((await duplicate.json()).booking.bookingId, id);
  await page.reload(); await page.waitForLoadState("networkidle");
  await page.getByRole("region", { name: "供应商订单结果" }).waitFor();
  assert.equal(await page.getByTestId("hotel-booking-id").innerText(), id);
  await page.getByRole("region", { name: "供应商订单结果" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: ".automation/hotel-trial-confirmed.png", fullPage: false });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => scrollTo({ top: 0, behavior: "instant" }));
  await page.screenshot({ path: ".automation/hotel-trial-mobile.png", fullPage: false });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ provider: "LiteAPI", environment: "sandbox", bookingId: id, status: current.booking.status, noExternalNavigation: true, duplicateSubmitUsesSameOrder: true, survivesReload: true, browserErrors: errors.length }));
} finally { await context.close(); await browser.close(); }
